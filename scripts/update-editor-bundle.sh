#!/usr/bin/env bash
# Rebuilds crates/rt-cef/ui/editor.bundle.js (CodeMirror for riptide://edit/)
# and its license notices from crates/rt-cef/editor/. Needs node and npm.
#   scripts/update-editor-bundle.sh          # the versions in package-lock.json
#   scripts/update-editor-bundle.sh --latest # update every package first
set -euo pipefail

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cd "$root/crates/rt-cef/editor"
if [[ ${1:-} == --latest ]]; then
  npm update --save-exact --no-fund --no-audit
else
  npm ci --no-fund --no-audit
fi

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
out=../ui
npx esbuild main.js --bundle --minify --format=iife --target=chrome120 \
  --legal-comments=none --log-level=error --metafile="$work/meta.json" \
  --banner:js="// Generated by scripts/update-editor-bundle.sh; licenses in editor.bundle.LICENSES.txt." \
  --outfile="$out/editor.bundle.js"
node notices.mjs "$work/meta.json" "$out/editor.bundle.LICENSES.txt"
echo "editor.bundle.js: $(wc -c < "$out/editor.bundle.js") bytes"
